/** Manifest paths deliberately not embedded (no `/v1/` twin to rewrite). */
export const V2_MANIFEST_OMITTED: readonly string[] = ['/.well-known/openwop', '/openapi.json'];

const V2_MATCHERS: readonly RegExp[] = V2_PATH_TEMPLATES.map(
  (t) => new RegExp(`^${t.replace(/[.:]/g, '\\$&').replace(/\{[A-Za-z]+\}/g, '[^/]+')}$`),
);

/**
 * The unversioned twin of a `/v1/<op>` path when `<op>` is a manifest-named
 * operation, else null. A query string is carried over untouched.
 */
export function v2Twin(path: string): string | null {
  const q = path.indexOf('?');
  const bare = q === -1 ? path : path.slice(0, q);
  const query = q === -1 ? '' : path.slice(q);
  if (!bare.startsWith('/v1/')) return null;
  const unversioned = bare.slice('/v1'.length);
  return V2_MATCHERS.some((m) => m.test(unversioned)) ? `${unversioned}${query}` : null;
}

/** Highest major the CLI implements among those the host advertises; 1 when the host says nothing usable. */
export function selectMajor(protocolVersions: unknown): ProtocolMajor {
  const advertised = Array.isArray(protocolVersions) ? protocolVersions.filter((v): v is string => typeof v === 'string') : [];
  for (const major of CLI_PROTOCOL_MAJORS) {
    if (advertised.some((v) => v.startsWith(`${major}.`))) return major;
  }
  return 1;
}

/**
 * Host-proprietary roots advertised in discovery `extensions` (versioning.md §5),
 * as `{ "/v1/host/<org>/": "/host/<org>/" }`. An entry needs a `root` under
 * `/host/<org>/`; its `twin` (when present) must be `/v1/host/<org>/…` and is
 * the prefix it replaces, else the twin is derived by prefixing `/v1`.
 */
export function hostRootsFrom(extensions: unknown): Record<string, string> {
  const roots: Record<string, string> = {};
  if (!extensions || typeof extensions !== 'object' || Array.isArray(extensions)) return roots;
  const withSlash = (s: string) => (s.endsWith('/') ? s : `${s}/`);
  for (const value of Object.values(extensions as Record<string, unknown>)) {
    if (!value || typeof value !== 'object') continue;
    const { root, twin } = value as { root?: unknown; twin?: unknown };
    if (typeof root !== 'string' || !/^\/host\/[^/]+(\/|$)/.test(root)) continue;
    const r = withSlash(root);
    const t = typeof twin === 'string' ? withSlash(twin) : `/v1${r}`;
    if (!/^\/v1\/host\/[^/]+\//.test(t)) continue;
    roots[t] = r;
  }
  return roots;
}

/** The advertised unversioned root for a `/v1/host/<org>/…` path, else null. */
export function hostRootFor(path: string, roots: Readonly<Record<string, string>>): string | null {
  if (!path.startsWith('/v1/host/')) return null;
  let best: string | null = null;
  for (const twin of Object.keys(roots)) {
    if (path.startsWith(twin) && (best === null || twin.length > best.length)) best = twin;
  }
  return best === null ? null : `${roots[best]}${path.slice(best.length)}`;
}

/**
 * Read `/.well-known/openwop` once and memoize the selected major (and, under
 * major 2, the advertised host-proprietary roots) on ctx.
 */
export async function negotiateMajor(ctx: Ctx): Promise<ProtocolMajor> {
  if (ctx.protocolMajor !== undefined) return ctx.protocolMajor;
  const pinned = ctx.env?.OPENWOP_PROTOCOL_MAJOR;
  if (pinned === '1' || pinned === '2') {
    ctx.protocolMajor = Number(pinned) as ProtocolMajor;
    ctx.hostRoots = {};
    return ctx.protocolMajor;
  }
  let major: ProtocolMajor = 1;
  let roots: Record<string, string> = {};
  try {
    const url = new URL('.well-known/openwop', ctx.baseUrl.endsWith('/') ? ctx.baseUrl : `${ctx.baseUrl}/`);
    const res = await ctx.fetchImpl(url, { method: 'GET', headers: { accept: 'application/json', 'openwop-version': '2' } });
    const doc = JSON.parse(await res.text()) as {
      protocolVersions?: unknown;
      extensions?: unknown;
      details?: { protocolVersions?: unknown };
    } | null;
    if (res.ok) {
      major = selectMajor(doc?.protocolVersions);
      if (major === 2) roots = hostRootsFrom(doc?.extensions);
    } else if (res.status === 406) {
      // §1.3: the host does not serve major 2 and echoes what it does serve.
      major = selectMajor(doc?.details?.protocolVersions);
    }
  } catch {
    // Unreachable or non-JSON discovery: stay on the v1 default (§1.3). The
    // command's own request reports the failure with its usual message.
  }
  ctx.protocolMajor = major;
  ctx.hostRoots = roots;
  return major;
}

/**
 * Rewrite a request for the negotiated major. Under major 2 a manifest-named
 * `/v1/<op>` becomes `/<op>` + `OpenWOP-Version: 2.0`, and a `/v1/host/<org>/…`
 * route becomes the host's advertised `/host/<org>/…` root (no version header).
 * Everything else — major 1, an already-unversioned path, a proprietary route
 * with no advertised root — passes through unchanged.
 */
export async function resolveRequest(
  ctx: Ctx,
  path: string,
  headers: Record<string, string>,
): Promise<{ path: string; headers: Record<string, string> }> {
  const major = await negotiateMajor(ctx);
  if (major !== 2) return { path, headers };
  const twin = v2Twin(path);
  if (twin !== null) return { path: twin, headers: { ...headers, 'openwop-version': '2.0' } };
  const rooted = hostRootFor(path, ctx.hostRoots ?? {});
  if (rooted !== null) return { path: rooted, headers };
  return { path, headers };
}
