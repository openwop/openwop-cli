import type { Ctx } from './context.js';
/**
 * Protocol-major negotiation — the one place the CLI decides which wire it speaks.
 *
 * `spec/v2/core/versioning.md` §1.5: a client selects the highest major it
 * implements that the host advertises in `protocolVersions[]`. This CLI
 * implements 2 and 1. Every command keeps its `/v1/<op>` literal; at the
 * request boundary (`resolveRequest`) two rewrites apply under major 2 only:
 *
 *  1. A literal whose unversioned twin is an operation named in
 *     `spec/v2/path-manifest.json` is rewritten to that twin with
 *     `OpenWOP-Version: 2.0` (§1.2 — the `/v1/` keys are the same operations
 *     through the overlap; §1.3 — the header selects major 2 on an unversioned
 *     name).
 *  2. A host-proprietary `/v1/host/<org>/…` literal (e.g. the reference host's
 *     `/v1/host/openwop-app/*`) is rewritten to the unversioned root the host
 *     advertises for that org under `extensions.*` (`{ root: "/host/<org>/",
 *     twin: "/v1/host/<org>/" }`, versioning.md §5), WITHOUT a version header —
 *     a `/host/<org>/…` path has no major and is outside §1.4. When no root is
 *     advertised the `/v1` twin is sent unchanged (it MAY ride the overlap).
 *
 * Anything else passes through exactly as written.
 *
 * Negotiation happens once per process: `/.well-known/openwop` is read ONCE
 * with `OpenWOP-Version: 2` so a dual-stack host answers with its v2
 * representation — the only one that carries the §5 `extensions.<org>.host`
 * mount (the header-less default is `preferredVersion`, i.e. the v1 document,
 * which does not). A host that does not serve major 2 answers `406` with
 * `details.protocolVersions` (§1.3), which is read the same way; a host that
 * ignores the header returns its only document. Both representations carry
 * `protocolVersions`. The major and the root map are memoized on
 * `ctx.protocolMajor` / `ctx.hostRoots`. `OPENWOP_PROTOCOL_MAJOR=1|2` pins the
 * major without a probe — the escape hatch for a host whose discovery lies;
 * under a pin no root is known, so `/v1/host/<org>/…` is sent unchanged.
 */

/** Majors this CLI implements, highest first (§1.5 precedence). */
export const CLI_PROTOCOL_MAJORS = [2, 1] as const;
export type ProtocolMajor = (typeof CLI_PROTOCOL_MAJORS)[number];

