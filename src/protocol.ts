/**
 * The protocol wire — the one place the CLI decides what a request carries.
 *
 * This CLI speaks OpenWOP protocol major 2 ONLY. Major 1 reached end of
 * support on 2026-10-04 (RFC 0234); a conformant host answers every `/v1/…`
 * path with `410`. Commands write the v2 path they send — the unversioned
 * operation name (`/runs`, `/agents/{agentId}`) or the host-proprietary root
 * (`/host/openwop-app/…`) — and `resolveRequest` only adds what the wire
 * needs, never rewrites a path:
 *
 *  1. `OpenWOP-Version: 2.0` on every protocol request (versioning.md §1.3 —
 *     the header selects major 2 on an unversioned name). A host-proprietary
 *     `/host/<org>/…` route the path manifest does not name carries NO version
 *     header: it has no major and is outside §1.4 (versioning.md §5).
 *  2. Tenant-bound `{runId}` segments travel projected (`acme~2Fr1`, never
 *     `%2F` — identity.md §5, src/ids.ts).
 *
 * Discovery is read ONCE per process with `OpenWOP-Version: 2` and memoized on
 * ctx (the document, the advertised stream origin). A host whose
 * `protocolVersions[]` (or a `406`'s `details.protocolVersions`) lists no `2.x`
 * is refused with a message naming major 1's end of support — the CLI never
 * falls back to `/v1`. An unreachable or non-JSON discovery is not a refusal:
 * the command's own request reports the failure with its usual message.
 * `OPENWOP_PROTOCOL_MAJOR=2` skips the discovery read (the escape hatch for a
 * host whose discovery lies); any other value is refused.
 */

/** Majors this CLI implements (§1.5 precedence). Major 1 ended support 2026-10-04 (RFC 0234). */
export const CLI_PROTOCOL_MAJORS = [2] as const;
export type ProtocolMajor = (typeof CLI_PROTOCOL_MAJORS)[number];

/** The one sentence every major-1 refusal carries. */
export const V1_END_OF_SUPPORT = 'OpenWOP protocol major 1 reached end of support on 2026-10-04 (RFC 0234); this CLI speaks only major 2.';

